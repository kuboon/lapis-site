#!/usr/bin/env python3
"""Vectorize the Théâtre Lapis logo (raster PNG -> SVG path).

Reads pages/static/media/2013/07/lapislogo.png and writes:
  - pages/static/lapis-logo.svg   standalone vector logo
  - pages/src/lapis-logo.ts       the same path, for inlining into pages

Requires Pillow, ImageMagick (`convert`), potrace and Deno (for `deno fmt`).

    python3 import/vectorize-logo.py
"""

import re
import subprocess
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "pages/static/media/2013/07/lapislogo.png"
OUT_SVG = ROOT / "pages/static/lapis-logo.svg"
OUT_TS = ROOT / "pages/src/lapis-logo.ts"

SCALE = 4  # trace at 4x for smooth curves
MARGIN = 10  # viewBox padding, in traced units


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)

        # Flatten the palette transparency onto white.
        im = Image.open(SRC).convert("RGBA")
        bg = Image.new("RGBA", im.size, "white")
        bg.alpha_composite(im)
        gray = bg.convert("L")

        # The hairline joining the "h" stem to its arch is an almost-white
        # 1px anti-aliased stroke in the source; darken it so it survives.
        px = gray.load()
        for y in range(81, 99):
            for x in range(137, 154):
                if px[x, y] < 253:
                    px[x, y] = 0
        gray.save(tmp / "src.png")

        # Upscale, blur away JPEG-ish jaggies, then threshold to a bitmap.
        subprocess.run(
            [
                "convert", tmp / "src.png",
                "-shave", "3x3", "-bordercolor", "white", "-border", "3",
                "-filter", "Lanczos", "-resize", f"{SCALE * 100}%",
                "-blur", "0x5", "-threshold", "55%",
                tmp / "logo.pbm",
            ],
            check=True,
        )
        subprocess.run(
            [
                "potrace", tmp / "logo.pbm", "-s", "-o", tmp / "logo.svg",
                "-t", "60", "-a", "1.25", "-O", "2", "--flat", "-u", "1",
            ],
            check=True,
        )
        trim = subprocess.run(
            ["convert", tmp / "logo.pbm", "-format", "%@", "info:"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout
        traced = (tmp / "logo.svg").read_text()

    w, h, x, y = map(int, re.match(r"(\d+)x(\d+)\+(\d+)\+(\d+)", trim).groups())
    view_box = f"{x - MARGIN} {y - MARGIN} {w + 2 * MARGIN} {h + 2 * MARGIN}"
    transform = re.search(r'<g transform="([^"]*)"', traced).group(1)
    transform = re.sub(r"(\d+)\.0+\b", r"\1", transform)
    d = re.sub(r"\s+", " ", re.search(r'<path d="([^"]*)"', traced).group(1))
    d = d.strip()

    OUT_SVG.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" '
        f'viewBox="{view_box}" role="img" aria-label="Théâtre Lapis">\n'
        f'<path transform="{transform}" d="{d}"/>\n'
        "</svg>\n"
    )
    OUT_TS.write_text(
        "// Generated by import/vectorize-logo.py — do not edit by hand.\n"
        "\n"
        "/** The Théâtre Lapis logo, traced from the original raster logo. */\n"
        "export const lapisLogo = {\n"
        f'  viewBox: "{view_box}",\n'
        f'  transform: "{transform}",\n'
        f'  d: "{d}",\n'
        "};\n"
    )
    # Match the repo's formatting so `deno task check` stays green.
    subprocess.run(["deno", "fmt", OUT_SVG, OUT_TS], cwd=ROOT / "pages", check=True)
    print(f"wrote {OUT_SVG.relative_to(ROOT)} and {OUT_TS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
